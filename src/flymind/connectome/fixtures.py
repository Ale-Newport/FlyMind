SIGN_POLICY = {
    "ACH": 1,
    "GABA": -1,
    "GLUT": -1,
    "DA": 1,
    "SER": 1,
    "OCT": 1,
    "HIST": -1,
    "UNKNOWN": 1,
}


@dataclass(frozen=True)
class FixtureInfo:
    dataset_id: str
    n_neurons: int
    n_edges: int


def build_fixture_tables(seed: int = FIXTURE_SEED) -> tuple[pd.DataFrame, pd.DataFrame]:
    rng = np.random.default_rng(seed)
    rows = []
    for cell_type, count, side, super_class, cell_class, nt, neuropil in _GROUPS:
        for k in range(count):
            if nt == "MIX":
                nt_k = rng.choice(
                    ["ACH", "GABA", "GLUT", "DA", "SER"], p=[0.6, 0.2, 0.15, 0.03, 0.02]
                )
            else:
                nt_k = nt
            rows.append(
                {
                    "name": f"{cell_type}_{k}",
                    "side": side,
                    "flow": {
                        "sensory": "afferent",
                        "descending": "efferent",
                        "motor": "efferent",
                    }.get(super_class, "intrinsic"),
                    "super_class": super_class,
                    "cell_class": cell_class,
                    "cell_sub_class": None,
                    "cell_type": cell_type,
                    "hemibrain_type": None,
                    "nt_type": str(nt_k),
                    "nt_confidence": np.float32(1.0),
                    "primary_neuropil": neuropil,
                }
            )
    df = pd.DataFrame(rows)
    n = len(df)
    # Unique synthetic int64 identifiers above 2**53 with random low bits.
    offsets = np.unique(rng.integers(1, 10**12, size=2 * n, dtype=np.int64))
    offsets = rng.permutation(offsets)[:n]
    if len(offsets) < n:
        raise RuntimeError("could not draw unique synthetic identifiers")
    df["root_id"] = (np.int64(ID_BASE) + offsets * 7919 + rng.integers(0, 7919, size=n)).astype(
        np.int64
    )
    centres = np.array([_NEUROPIL_CENTRES[p] for p in df["primary_neuropil"]])
    spread = np.where(df["cell_class"].eq("background").to_numpy()[:, None], 45e3, 18e3)
    df[["pos_x", "pos_y", "pos_z"]] = (centres + rng.normal(0, 1, (n, 3)) * spread).astype(
        np.float32
    )
    # df is in group order; assign idx by sorted root_id (canonical rule).
    df = df.sort_values("root_id", kind="stable").reset_index(drop=True)
    df.insert(0, "idx", np.arange(n, dtype=np.int32))

    by_type = df.groupby("cell_type")["idx"].apply(np.array).to_dict()
    pre_l, post_l, cnt_l = [], [], []
    for pre_t, post_t, p, (lo, hi) in _DESIGNED:
        pre_ids, post_ids = by_type[pre_t], by_type[post_t]
        mask = rng.random((len(pre_ids), len(post_ids))) < p
        pi, qi = np.nonzero(mask)
        pre_l.append(pre_ids[pi])
        post_l.append(post_ids[qi])
        cnt_l.append(rng.integers(lo, hi + 1, size=len(pi)))
    # Sparse random background (and weak links from background into designed groups).
    bg = df.index[df["cell_class"].eq("background")].to_numpy()
    allidx = df["idx"].to_numpy()
    n_out = 12
    pre_bg = np.repeat(bg, n_out)
    # Background never targets descending/motor groups, so their activity comes only
    # from the designed pathways (keeps the demonstration interpretable).
    bg_targets = allidx[~df["super_class"].isin(["descending", "motor"]).to_numpy()]
    post_bg = rng.choice(bg_targets, size=len(pre_bg))
    pre_l.append(pre_bg)
    post_l.append(post_bg)
    cnt_l.append(np.clip(rng.lognormal(1.6, 0.6, size=len(pre_bg)).astype(int), 1, 40))
    # Designed groups also feed background (so propagation is visible across regions).
    designed = df.index[~df["cell_class"].isin(["background", "test_chain"])].to_numpy()
    pre_d = np.repeat(designed, 3)
    post_d = rng.choice(bg, size=len(pre_d))
    pre_l.append(pre_d)
    post_l.append(post_d)
    cnt_l.append(rng.integers(5, 12, size=len(pre_d)))

    edges = pd.DataFrame(
        {
            "pre_idx": np.concatenate(pre_l).astype(np.int32),
            "post_idx": np.concatenate(post_l).astype(np.int32),
            "syn_count": np.concatenate(cnt_l).astype(np.int32),
        }
    )
    # Keep the test chain isolated from background input for deterministic tests.
    chain = (
        set(by_type["syn_chain_A"])
        | set(by_type["syn_chain_B"])
        | set(by_type["syn_chain_C"])
        | set(by_type["syn_chain_I"])
    )
    designed_chain = edges["pre_idx"].isin(chain) & edges["post_idx"].isin(chain)
    edges = edges[~edges["post_idx"].isin(chain) | designed_chain]
    edges = edges.groupby(["pre_idx", "post_idx"], as_index=False)["syn_count"].sum()
    nt = df["nt_type"].to_numpy()
    edges["sign"] = np.array([SIGN_POLICY[x] for x in nt[edges["pre_idx"].to_numpy()]], np.int8)

    # Derived per-neuron synapse totals.
    df["output_synapses"] = np.bincount(
        edges["pre_idx"], weights=edges["syn_count"], minlength=n
    ).astype(np.int64)
    df["input_synapses"] = np.bincount(
        edges["post_idx"], weights=edges["syn_count"], minlength=n
    ).astype(np.int64)
    return df, edges


def build_fixture(out_root: Path, seed: int = FIXTURE_SEED) -> FixtureInfo:
    from flymind.connectome.store import write_dataset

    neurons, edges = build_fixture_tables(seed)
    out_dir = out_root / FIXTURE_ID
    manifest = DatasetManifest(
        dataset_id=FIXTURE_ID,
        dataset_name="FlyMind synthetic demonstration network",
        dataset_version="1",
        specimen="none (synthetic; generated by flymind.connectome.fixtures)",
        adapter="SyntheticFixture",
        synthetic=True,
        source="Generated deterministically by FlyMind code (seed recorded in filters).",
        license="MIT (generated by FlyMind)",
        citations=[Citation(text="Synthetic data; no citation applies.")],
        imported_at=utc_now(),
        transformations=[
            "neurons sorted by root_id; dense idx assigned",
            "edges aggregated by (pre_idx, post_idx)",
            "edge sign from presynaptic nt_type via SIGN_POLICY",
        ],
        filters={"seed": seed},
        sign_policy=SIGN_POLICY,
        sign_policy_source="FlyMind default (GABA/GLUT/HIST inhibitory; others excitatory)",
        n_neurons=len(neurons),
        n_source_connections=len(edges),
        n_edges=len(edges),
        n_synapses=int(edges["syn_count"].sum()),
        processing=runtime_provenance(),
        notes=[
            "SYNTHETIC DEMONSTRATION DATA. Not a connectome of any animal.",
            "Designed pathways were wired by hand to exercise the closed-loop pipeline.",
        ],
    )
    write_dataset(out_dir, neurons, edges, manifest)
    validate_and_record(out_dir)
    return FixtureInfo(FIXTURE_ID, len(neurons), len(edges))
