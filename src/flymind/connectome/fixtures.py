"""Deterministic SYNTHETIC connectome fixture for tests and demonstration mode.

This network is *not* derived from any real fly. It is generated by code, labelled
``synthetic=True`` in its manifest, uses ``syn_``-prefixed cell types and ``SYN-``
neuropil names, and identifiers in a range that FlyWire never uses (>= 9.9e17), so
it can never be mistaken for FlyWire data.

It contains three kinds of structure:

1. *Designed demonstration pathways* (sensory -> projection -> lateral -> descending)
   wired by hand so that the closed-loop virtual-fly pipeline can be exercised
   without the real dataset. Any behaviour they produce is a DEMONSTRATION of the
   software pipeline, not a biological finding.
2. A *test chain* (A -> B -> C with inhibitory I -> C) with known propagation
   used by integration tests.
3. Sparse random background connectivity.
"""

