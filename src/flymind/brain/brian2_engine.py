"""Brian2 reference engine (validation backend).

Builds the Shiu et al. (2024) model in Brian2 with the same equations, reset,
refractoriness, delays and weights as the reference code
(github.com/philshiu/Drosophila_brain_model, model.py), and runs it on the exact
same external input spike events as :class:`~flymind.brain.engine.LIFEngine`.

The only intentional difference from the reference code: Poisson input spikes are
pre-generated by FlyMind (seeded NumPy) and delivered through a
``SpikeGeneratorGroup`` with zero-delay ``on_pre='v += w'`` synapses instead of
Brian2's internal ``PoissonInput``. Both act in the ``synapses`` slot of the same
time step with the same weight (f_poi * w_syn), so the dynamics are identical while
the random input becomes reproducible and shareable between engines.

Supported: Poisson/pulse stimuli, current stimuli, ``block_output`` silencing and
synaptic scaling. Not supported here: ``clamp`` silencing (raises).
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from flymind.brain.engine import LIFEngine
from flymind.brain.stimulus import CurrentStimulus, Silencing


@dataclass
class Brian2Result:
    spike_steps: np.ndarray
    spike_local: np.ndarray
    probe_v: np.ndarray  # (n_steps, n_probes) in mV, recorded after each step
    wall_build_s: float
    wall_run_s: float


def run_brian2(engine: LIFEngine, n_steps: int, codegen: str = "cython") -> Brian2Result:
    """Run ``n_steps`` from the engine's *initial* state using Brian2."""
    import time

    import brian2 as b2

    if any(isinstance(i, Silencing) and i.mode == "clamp" for i in engine.interventions):
        raise NotImplementedError("Brian2 reference engine does not implement clamp silencing")
    t_build = time.perf_counter()
    b2.start_scope()
    b2.prefs.codegen.target = codegen
    p = engine.params
    dt = p.dt_ms * b2.ms
    b2.defaultclock.dt = dt
    ns = {
        "v_0": p.v_rest_mV * b2.mV,
        "v_rst": p.v_reset_mV * b2.mV,
        "v_th": p.v_threshold_mV * b2.mV,
        "t_mbr": p.tau_m_ms * b2.ms,
        "tau": p.tau_syn_ms * b2.ms,
    }
    g_flag = "(unless refractory)" if p.hold_g_during_refractory else ""
    eqs = f"""
    dv/dt = (v_0 - v + g + I) / t_mbr : volt (unless refractory)
    dg/dt = -g / tau               : volt {g_flag}
    rfc                            : second
    I                              : volt
    """
    reset = "v = v_rst; g = 0 * mV" if p.reset_g else "v = v_rst"
    net = engine.network
    neu = b2.NeuronGroup(
        net.n,
        eqs,
        method="linear",
        threshold="v > v_th",
        reset=reset,
        refractory="rfc",
        namespace=ns,
        name="neurons",
    )
    neu.v = p.v_rest_mV * b2.mV
    neu.g = 0 * b2.mV
    neu.rfc = engine._ref_steps() * dt  # per-neuron (0 for stimulated targets)

    graph = net.graph
    syn = b2.Synapses(
        neu, neu, "w : volt", on_pre="g += w", delay=p.delay_ms * b2.ms, name="recurrent"
    )
    pre = graph.pre_indices()
    syn.connect(i=pre, j=np.asarray(graph.indices, dtype=np.int64))
    syn.w = np.asarray(engine.weights, dtype=np.float64) * b2.mV

    objects = [neu, syn]
    ext_steps, ext_idx, ext_w = engine._events(0, n_steps)
    if len(ext_steps):
        # one generator unit per (target, weight, duplicate-rank)
        keys = np.stack([ext_idx, np.round(ext_w * 1e9).astype(np.int64)], axis=1)
        uniq, inv = np.unique(keys, axis=0, return_inverse=True)
        inv = inv.ravel()
        order = np.lexsort((inv, ext_steps))
        st, un = ext_steps[order], inv[order]
        rank = np.zeros(len(st), dtype=np.int64)
        same = np.r_[False, (st[1:] == st[:-1]) & (un[1:] == un[:-1])]
        for k in np.nonzero(same)[0]:
            rank[k] = rank[k - 1] + 1
        gen_index = rank * len(uniq) + un
        n_gen = int(gen_index.max()) + 1
        gen = b2.SpikeGeneratorGroup(n_gen, gen_index, st * dt, name="inputs")
        gsyn = b2.Synapses(gen, neu, "w : volt", on_pre="v += w", name="input_syn")
        gen_target = uniq[np.arange(n_gen) % len(uniq), 0]
        gsyn.connect(i=np.arange(n_gen), j=gen_target)
        gsyn.w = uniq[np.arange(n_gen) % len(uniq), 1] / 1e9 * b2.mV
        objects += [gen, gsyn]

    spk = b2.SpikeMonitor(neu, name="spikes")
    objects.append(spk)
    probe = None
    if len(engine.probe_local):
        probe = b2.StateMonitor(
            neu, "v", record=engine.probe_local.tolist(), when="end", name="probe"
        )
        objects.append(probe)
    network = b2.Network(*objects)

    # Current stimuli: run in segments between window boundaries, setting I.
    bounds = sorted({0, n_steps, *[b for b in engine._current_boundaries() if 0 < b < n_steps]})
    wall_build = time.perf_counter() - t_build
    t_run = time.perf_counter()
    for a, b in zip(bounds[:-1], bounds[1:], strict=True):
        drive = engine._drive_at(a * p.dt_ms)
        neu.I = np.asarray(drive, dtype=np.float64) * b2.mV
        network.run((b - a) * dt, namespace=ns)
    wall_run = time.perf_counter() - t_run

    steps = np.round(np.asarray(spk.t / dt)).astype(np.int64)
    order = np.lexsort((np.asarray(spk.i), steps))
    probe_v = np.asarray(probe.v / b2.mV).T if probe is not None else np.zeros((n_steps, 0))
    return Brian2Result(
        steps[order], np.asarray(spk.i, dtype=np.int64)[order], probe_v, wall_build, wall_run
    )


__all__ = ["Brian2Result", "CurrentStimulus", "run_brian2"]
