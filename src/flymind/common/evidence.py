"""Scientific evidence categories used to label every claim, result and UI element."""

from __future__ import annotations

from enum import StrEnum


class Evidence(StrEnum):
    PUBLISHED = "published"
    """Supported by peer-reviewed literature (citation required)."""
    REPRODUCED = "reproduced"
    """A published result re-obtained by running this repository (evidence file required)."""
    SIMULATION = "simulation_output"
    """Produced by FlyMind's models without independent biological confirmation."""
    HYPOTHESIS = "hypothesis"
    """A proposed interpretation or open experimental question."""
    DEMONSTRATION = "demonstration"
    """Illustrative or synthetic behaviour (e.g. synthetic fixtures, scripted controllers)."""


EVIDENCE_DESCRIPTIONS: dict[Evidence, str] = {
    Evidence.PUBLISHED: "Supported by peer-reviewed scientific literature.",
    Evidence.REPRODUCED: "A published result re-obtained by running FlyMind.",
    Evidence.SIMULATION: "Generated by FlyMind's models; not independently confirmed in a fly.",
    Evidence.HYPOTHESIS: "A proposed interpretation or experimental question.",
    Evidence.DEMONSTRATION: "Illustrative or synthetic behaviour; not a biological claim.",
}
