export const fmt = {
  int: (n: number | null | undefined) => (n == null ? "–" : n.toLocaleString()),
  num: (n: number | null | undefined, d = 1) => (n == null || Number.isNaN(n) ? "–" : n.toFixed(d)),
  ms: (n: number) => (n >= 1000 ? `${(n / 1000).toFixed(2)} s` : `${n.toFixed(1)} ms`),
};

// ------------------------------------------------------------ data pickers
export function useDatasets() {
  return useAsync<DatasetSummary[]>(() => api.datasets(), []);
}

export function DatasetPicker({ compact = false }: { compact?: boolean }) {
  const { datasetId, setDatasetId } = useApp();
  const { data } = useDatasets();
  useEffect(() => {
    if (data && data.length && !data.some((d) => d.dataset_id === datasetId)) setDatasetId(data[0].dataset_id);
  }, [data, datasetId, setDatasetId]);
  return (
    <select aria-label="Dataset" className={`input ${compact ? "w-auto py-1 text-xs" : ""}`} value={datasetId} onChange={(e) => setDatasetId(e.target.value)}>
      {(data ?? []).map((d) => (
        <option key={d.dataset_id} value={d.dataset_id}>
          {d.synthetic ? "Synthetic demo" : `${d.name} v${d.version}`} ({d.n_neurons.toLocaleString()} neurons)
        </option>
      ))}
    </select>
  );
}

/** Choose neurons by curated group, root IDs, or cell type. */
export function SelectorInput({ datasetId, value, onChange }: { datasetId: string; value: Selector; onChange: (s: Selector) => void }) {
  const groups = useAsync<Group[]>(() => api.groups(datasetId), [datasetId]);
  const mode = value.group ? "group" : value.root_ids?.length ? "ids" : value.cell_types?.length ? "type" : "group";
  const [m, setM] = useState(mode);
  return (
    <div className="space-y-1.5">
      <div className="flex gap-1 text-xs" role="tablist" aria-label="Selection method">
        {(["group", "ids", "type"] as const).map((k) => (
          <button key={k} role="tab" aria-selected={m === k} className={`btn px-2 py-0.5 text-xs ${m === k ? "btn-primary" : ""}`} onClick={() => setM(k)}>
            {{ group: "Group", ids: "Root IDs", type: "Cell type" }[k]}
          </button>
        ))}
      </div>
      {m === "group" && (
        <select aria-label="Neuron group" className="input" value={value.group ?? ""} onChange={(e) => onChange({ group: e.target.value })}>
          <option value="">— choose a group —</option>
          {(groups.data ?? []).map((g) => (
            <option key={g.name} value={g.name} title={g.description}>{g.name} ({g.n_neurons})</option>
          ))}
        </select>
      )}
      {m === "ids" && (
        <input aria-label="Root IDs" className="input mono" placeholder="comma-separated root IDs"
          value={(value.root_ids ?? []).join(",")}
          onChange={(e) => onChange({ root_ids: e.target.value.split(/[\s,;]+/).filter(Boolean) })} />
      )}
      {m === "type" && (
        <input aria-label="Cell type" className="input" placeholder="e.g. DNa02, ORN_DM1"
          value={(value.cell_types ?? []).join(",")}
          onChange={(e) => onChange({ cell_types: e.target.value.split(/[\s,;]+/).filter(Boolean) })} />
      )}
    </div>
  );
}

