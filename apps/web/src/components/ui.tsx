// ------------------------------------------------------------------ hooks
export function useAsync<T>(fn: () => Promise<T>, deps: unknown[]) {
  const [state, setState] = useState<{ data: T | null; error: Error | null; loading: boolean }>({
    data: null, error: null, loading: true,
  });
  const [nonce, setNonce] = useState(0);
  useEffect(() => {
    let alive = true;
    setState((s) => ({ ...s, loading: true, error: null }));
    fn().then(
      (data) => alive && setState({ data, error: null, loading: false }),
      (error: Error) => alive && setState({ data: null, error, loading: false }),
    );
    return () => { alive = false; };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [...deps, nonce]);
  return { ...state, reload: () => setNonce((n) => n + 1) };
}

export function useInterval(cb: () => void, ms: number | null) {
  const ref = useRef(cb);
  ref.current = cb;
  useEffect(() => {
    if (ms === null) return;
    const id = setInterval(() => ref.current(), ms);
    return () => clearInterval(id);
  }, [ms]);
}

// ------------------------------------------------------------- primitives
const EVIDENCE: Record<Evidence, { label: string; cls: string; tip: string }> = {
  published: { label: "Published", cls: "border-sky-400/50 text-sky-300 bg-sky-400/10", tip: "Supported by peer-reviewed literature." },
  reproduced: { label: "Reproduced", cls: "border-emerald-400/50 text-emerald-300 bg-emerald-400/10", tip: "A published result re-obtained by running FlyMind (see docs/evidence)." },
  simulation_output: { label: "Simulation output", cls: "border-amber-400/50 text-amber-300 bg-amber-400/10", tip: "Generated by FlyMind's model; not independently confirmed in a fly." },
  hypothesis: { label: "Hypothesis", cls: "border-violet-400/50 text-violet-300 bg-violet-400/10", tip: "A proposed interpretation or open question being tested." },
  demonstration: { label: "Demonstration", cls: "border-slate-400/50 text-slate-300 bg-slate-400/10", tip: "Illustrative or synthetic; not a biological claim." },
};

export function EvidenceBadge({ kind, className = "" }: { kind: Evidence | null | undefined; className?: string }) {
  if (!kind || !(kind in EVIDENCE)) return null;
  const e = EVIDENCE[kind];
  return (
    <span className={`chip ${e.cls} ${className}`} title={e.tip} data-testid={`evidence-${kind}`}>
      {e.label}
    </span>
  );
}

