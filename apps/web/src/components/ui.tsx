// ------------------------------------------------------------------ hooks
export function useAsync<T>(fn: () => Promise<T>, deps: unknown[]) {
  const [state, setState] = useState<{ data: T | null; error: Error | null; loading: boolean }>({
    data: null, error: null, loading: true,
  });
  const [nonce, setNonce] = useState(0);
  useEffect(() => {
    let alive = true;
    setState((s) => ({ ...s, loading: true, error: null }));
    fn().then(
      (data) => alive && setState({ data, error: null, loading: false }),
      (error: Error) => alive && setState({ data: null, error, loading: false }),
    );
    return () => { alive = false; };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [...deps, nonce]);
  return { ...state, reload: () => setNonce((n) => n + 1) };
}

export function useInterval(cb: () => void, ms: number | null) {
  const ref = useRef(cb);
  ref.current = cb;
  useEffect(() => {
    if (ms === null) return;
    const id = setInterval(() => ref.current(), ms);
    return () => clearInterval(id);
  }, [ms]);
}

// ------------------------------------------------------------- evidence marks
// Marks work like footnote symbols: colour and shape both carry the category.
const EVIDENCE: Record<Evidence, { label: string; color: string; shape: "square" | "circle" | "diamond" | "diamond-o" | "circle-o"; tip: string }> = {
  published: { label: "Published", color: "var(--ev-published)", shape: "square", tip: "Supported by peer-reviewed literature." },
  reproduced: { label: "Reproduced", color: "var(--ev-reproduced)", shape: "circle", tip: "A published result re-obtained by running FlyMind (see docs/evidence)." },
  simulation_output: { label: "Simulation output", color: "var(--ev-simulation)", shape: "diamond", tip: "Generated by FlyMind's model; not independently confirmed in a fly." },
  hypothesis: { label: "Hypothesis", color: "var(--ev-hypothesis)", shape: "diamond-o", tip: "A proposed interpretation or open question being tested." },
  demonstration: { label: "Demonstration", color: "var(--ev-demonstration)", shape: "circle-o", tip: "Illustrative or synthetic; not a biological claim." },
};

export function EvidenceMark({ kind, size = 9 }: { kind: Evidence; size?: number }) {
  const e = EVIDENCE[kind];
  const hollow = e.shape.endsWith("-o");
  const base = e.shape.replace("-o", "");
  const common = { fill: hollow ? "none" : e.color, stroke: e.color, strokeWidth: 1.3 };
  return (
    <svg width={size} height={size} viewBox="0 0 10 10" aria-hidden style={{ flex: "none" }}>
      {base === "square" && <rect x="1" y="1" width="8" height="8" {...common} />}
      {base === "circle" && <circle cx="5" cy="5" r="4" {...common} />}
      {base === "diamond" && <path d="M5 .6 9.4 5 5 9.4.6 5Z" {...common} />}
    </svg>
  );
}

export const EVIDENCE_KINDS = Object.keys(EVIDENCE) as Evidence[];
export const evidenceText = (k: Evidence) => EVIDENCE[k];

/** Evidence category as a typographic mark: a small shape in the category colour, then the name. */
export function EvidenceBadge({ kind, className = "" }: { kind: Evidence | null | undefined; className?: string }) {
  if (!kind || !(kind in EVIDENCE)) return null;
  const e = EVIDENCE[kind];
  return (
    <span className={`ev ${className}`} title={e.tip} data-testid={`evidence-${kind}`}>
      <EvidenceMark kind={kind} />
      {e.label}
    </span>
  );
}

// ------------------------------------------------------------- notices
export function Notice({ tone = "neutral", children, role, className = "" }: { tone?: "neutral" | "warn" | "danger" | "info" | "accent"; children: ReactNode; role?: string; className?: string }) {
  const t = tone === "neutral" ? "" : `note-${tone}`;
  return <div role={role} className={`note ${t} ${className}`}>{children}</div>;
}

export function SyntheticBanner({ show }: { show: boolean }) {
  if (!show) return null;
  return (
    <Notice tone="warn" role="note">
      Synthetic demonstration data, generated by FlyMind code. It is not the connectome of any animal.
    </Notice>
  );
}

export function ErrorBox({ error, onRetry }: { error: Error | null; onRetry?: () => void }) {
  if (!error) return null;
  const backend = error instanceof BackendRequiredError;
  return (
    <Notice tone={backend ? "info" : "danger"} role="alert">
      <span className="min-w-0 break-words">{error.message}</span>
      {onRetry && !backend && <button className="btn btn-link ml-3 text-xs" onClick={onRetry}>Retry</button>}
    </Notice>
  );
}

