export function ErrorBox({ error, onRetry }: { error: Error | null; onRetry?: () => void }) {
  if (!error) return null;
  const backend = error instanceof BackendRequiredError;
  return (
    <div role="alert" className={`rounded-lg border px-3 py-2 text-sm ${backend ? "border-sky-500/40 bg-sky-500/10 text-sky-200" : "border-rose-500/40 bg-rose-500/10 text-rose-200"}`}>
      {error.message}
      {onRetry && !backend && <button className="btn ml-3 py-0.5 text-xs" onClick={onRetry}>Retry</button>}
    </div>
  );
}

