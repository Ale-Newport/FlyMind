/** Key-value list. Rows: [label, value, unit?]; falsy rows are skipped. */
export function KV({ rows, className = "", flush = false, testId }: { rows: (readonly [ReactNode, ReactNode, string?] | null | false | undefined | "")[]; className?: string; flush?: boolean; testId?: string }) {
  return (
    <dl className={`kv ${flush ? "kv-flush" : ""} ${className}`} data-testid={testId}>
      {rows.filter(Boolean).map((r, i) => {
        const [k, v, unit] = r as readonly [ReactNode, ReactNode, string?];
        return (
          <div key={i}>
            <dt>{k}</dt>
            <dd>{v}{unit && v !== "–" && <span className="unit" style={unit.startsWith("°") ? { marginLeft: 0 } : undefined}>{unit}</span>}</dd>
          </div>
        );
      })}
    </dl>
  );
}

